$running = @(Get-CimInstance Win32_Process -Filter "Name = 'LanPrint.exe' OR Name = 'lan-print.exe'")
$targets = @()
foreach ($relative in $files) {
    $candidate = Join-Path $cleanupRoot $relative
    if (-not (Test-Path -LiteralPath $candidate)) { continue }
    $item = Get-Item -LiteralPath $candidate -Force
    if ($item.PSIsContainer -or ($item.Attributes -band [IO.FileAttributes]::ReparsePoint)) { throw "Unexpected entry: $candidate" }
    if (-not $item.FullName.StartsWith($cleanupRoot + '\', [StringComparison]::OrdinalIgnoreCase)) { throw "Unexpected path: $candidate" }
    $parent = $item.Directory
    while ($parent.FullName -ne $cleanupRoot) {
        if ($parent.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw "Linked directory: $($parent.FullName)" }
        $parent = $parent.Parent
    }
    $top = Join-Path $cleanupRoot ($relative.Split('/')[0])
    if (@($running | Where-Object { $_.CommandLine -and $_.CommandLine.IndexOf($top, [StringComparison]::OrdinalIgnoreCase) -ge 0 }).Count) { throw "Test directory is still in use: $top" }
    $targets += $item.FullName
}
foreach ($target in $targets) { Remove-Item -LiteralPath $target -Force }
foreach ($relative in $directories) {
    $directory = Join-Path $cleanupRoot $relative
    if ((Test-Path -LiteralPath $directory) -and @(Get-ChildItem -LiteralPath $directory -Force).Count -eq 0) {
        Remove-Item -LiteralPath $directory
    }
}
Write-Output "Removed $($targets.Count) confirmed obsolete files; only empty directories were removed."
